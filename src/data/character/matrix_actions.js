// The full Matrix Actions list — confirmed against source (Matrix
// chapters, Part 1 & 2). No target-side simulation, matching the
// project's explicit boundary: the opposing dice pool is always
// something the GM tells the player, never looked up or computed from
// any stored data (Hacked Devices is notes, not a target model). This
// file only captures the PLAYER'S side: which skill/attribute rolls,
// what it's opposed by (as reference text), access level required,
// action type, legality, and the real rules effect.
//
// accessLevels: which access tier(s) the action is usable at — most
// allow any of Outsider/User/Admin; several require User/Admin or
// Admin specifically. actionType: 'minor' | 'major' | 'extended' |
// 'anytime'. linkedAttribute ('attack' | 'sleaze' | null): actions
// explicitly tied to one of those two — relevant to the "using an
// action linked to your LOWER attribute costs a dice pool penalty
// equal to the gap" rule. skill/attribute: the actual roll — several
// actions pair a skill with a NON-default attribute (Hide uses
// Cracking+Intuition, not Cracking+Logic), so attribute is stored
// explicitly per action rather than assumed from the skill's own
// primaryAttribute.

